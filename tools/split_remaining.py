# split a ne!(...) entry line into fields for keying
def entry_key(line):
    m = re.search(r'ne!\("([^"]+)",\s*"([^"]+)",\s*"([^"]+)"', line)
    return (m.group(1), m.group(2), m.group(3)) if m else None

def entry_class(line):
    m = re.search(r'ne!\("([^"]+)",', line)
    return m.group(1) if m else None

def split_table_entries(src, start_idx, keep_fn, drop_fn=None):
    """Scan table entries (lines starting with ne! or comments) from start_idx;
    route each ne! line via keep_fn(cls)->bool. Returns (keep_lines, moved_by_keep).
    """
    keep, moved = [], []
    for line in src[start_idx:]:
        stripped = line.strip()
        if stripped.startswith('//') or not stripped:
            continue
        if stripped.startswith('ne!('):
            cls = entry_class(line)
            if drop_fn and drop_fn(line):
                continue
            if keep_fn(cls):
                keep.append(line)
            else:
                moved.append(line)
    return keep, moved

def strip_blank_ends(lines):
    while lines and lines[0].strip() == '':
        lines.pop(0)
    while lines and lines[-1].strip() == '':
        lines.pop()
    return lines

# ---------------------------------------------------------------- keiyoushi.rs table entries
TABLE_START = next(i for i, l in enumerate(ky) if 'pub const KEIYOUSHI_TABLE' in l)
def is_kanade(cls):
    return cls.startswith('Leu/kanade/') and not cls.startswith('Leu/kanade/tachiyomi/util/JsoupExtensionsKt')
def is_jsoup(cls):
    return cls.startswith('Lorg/jsoup/') or cls.startswith('Leu/kanade/tachiyomi/util/JsoupExtensionsKt')
def is_okhttp3(cls):
    return cls.startswith('Lokhttp3/')
def is_kotlin(cls):
    return cls.startswith('Lkotlin/')
def is_android(cls):
    return cls.startswith('Landroid')  # android. + androidx.

keep_kanade, moved_entries = [], []
buckets = {'okhttp3': [], 'jsoup': [], 'kotlin': [], 'android': []}
for line in ky[TABLE_START:]:
    stripped = line.strip()
    if not stripped.startswith('ne!('):
        continue
    cls = entry_class(line)
    if is_kanade(cls):
        keep_kanade.append(line)
    elif is_jsoup(cls):
        buckets['jsoup'].append(line)
    elif is_okhttp3(cls):
        buckets['okhttp3'].append(line)
    elif is_kotlin(cls):
        buckets['kotlin'].append(line)
    elif is_android(cls):
        buckets['android'].append(line)
    else:
        print('UNROUTED:', line.strip()[:100])
        sys.exit(1)

# OKHTTP_TABLE entries from mod.rs
