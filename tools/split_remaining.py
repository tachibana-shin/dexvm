mod_ok = mod[okhttp_tbl_start:okhttp_tbl_end + 1]
ok_kanade, ok_okhttp3 = [], []
for line in mod_ok:
    stripped = line.strip()
    if not stripped.startswith('ne!('):
        continue
    cls = entry_class(line)
    if is_kanade(cls) or cls.startswith('Leu/kanade/'):
        ok_kanade.append(line)
    elif is_okhttp3(cls):
        ok_okhttp3.append(line)
    else:
        print('UNROUTED OKHTTP_TABLE:', line.strip()[:100])
        sys.exit(1)

# dedupe okhttp3 entries: keiyoushi version wins (it was registered later)
seen = set()
ok_okhttp3_final = []
for line in buckets['okhttp3']:
    key = entry_key(line)
    seen.add(key)
    ok_okhttp3_final.append(line)
dropped = []
for line in ok_okhttp3:
    key = entry_key(line)
    if key in seen:
        dropped.append(key)
        continue
    seen.add(key)
    ok_okhttp3_final.append(line)

# eu.kanade entries from OKHTTP_TABLE: skip HttpSource getHeaders (dup, default wins)
for line in ok_kanade:
    key = entry_key(line)
    dup = any(entry_key(k) == key for k in keep_kanade)
    if dup:
        dropped.append(key)
        continue
    keep_kanade.append(line)

print(f'kanade entries: {len(keep_kanade)}  okhttp3: {len(ok_okhttp3_final)}  '
      f'jsoup: {len(buckets["jsoup"])}  kotlin: {len(buckets["kotlin"])}  android: {len(buckets["android"])}')
print('dropped dup keys:', dropped)


def extract_fns(lines, names):
    """Return just the whole fns (signature through closing brace) whose signature
    contains any of `names`, in order."""
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if any(n in line for n in names):
            depth = 0
            start = i
            while i < len(lines):
                depth += lines[i].count('{') - lines[i].count('}')
                i += 1
                if depth == 0:
                    break
            out.extend(lines[start:i])
        else:
            i += 1
    return out


def drop_fns(lines, names):
    """Remove whole fns (signature line through the matching closing brace) whose
    signature contains any of `names`."""
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if any(n in line for n in names):
            depth = 0
            start = i
            while i < len(lines):
                depth += lines[i].count('{') - lines[i].count('}')
                i += 1
                if depth == 0:
                    break
        else:
            out.append(line)
            i += 1
    return out

