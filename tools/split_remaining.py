"""Final native-table split: keiyoushi.rs -> keiyoushi(kanade)/okhttp/jsoup/android/kotlin,
mod.rs NATIVE_TABLE -> kotlin.rs/injekt.rs, rewrite mod.rs + package mod files.

Run AFTER tools/split_lang.py and tools/split_util.py. One-shot; not idempotent.
"""
import os
import re
import sys

ROOT = os.environ.get('OUT', 'src/vm/native')

def read(p):
    """Read a source file from git HEAD (the pre-refactor tree); fall back to the
    on-disk output tree for files generated by an earlier split script."""
    import subprocess
    disk = p
    if p.startswith(ROOT):  # remap OUT back to the repo-relative source path
        p = 'src/vm/native' + p[len(ROOT):]
    r = subprocess.run(['git', 'show', f'HEAD:{p}'], capture_output=True, text=True)
    if r.returncode == 0:
        return r.stdout.split('\n')
    with open(disk) as f:  # generated by an earlier split script
        return f.read().split('\n')

def write(p, text):
    with open(p, 'w') as f:
        f.write(text)

def lines_1based(src, a, b):
    """1-based inclusive slice."""
    return src[a - 1:b]

def lines_1based_keep(src, *ranges):
    out = []
    for a, b in ranges:
        out.extend(src[a - 1:b])
    return out

def banner(title):
    return f'// ---------------------------------------------------------------------------\n// {title}\n// ---------------------------------------------------------------------------\n\n'

# ---------------------------------------------------------------- sources
ky = read(f'{ROOT}/keiyoushi.rs')
